statuses = ["ToDo","InProgress","Review","Done"]
priorities = ["Low","Medium","High"]
users = ["anna","john","maria","alex","ivan","olga"]

rows = []

for i in range(1, 3001):
    task_type = random.choice(list(titles_by_type.keys()))
    title = random.choice(titles_by_type[task_type])
    
    if task_type == "Авторизация":
        possible_desc = descriptions[:15]
    elif task_type == "База данных":
        possible_desc = descriptions[12:30]
    elif task_type == "Интерфейс":
        possible_desc = descriptions[15:45]
    else:
        possible_desc = descriptions[25:60]
    
    description = random.choice(possible_desc)
    
    status = random.choices(statuses, weights=[0.25,0.35,0.2,0.2])[0]
    priority = random.choices(priorities, weights=[0.3,0.5,0.2])[0]
    assigned = "|".join(random.sample(users, k=random.randint(1,2)))
    created = datetime(2026,1,1) + timedelta(days=random.randint(0,100))
    updated = created + timedelta(days=random.randint(0,20)) if random.random() < 0.7 else None
    taskcode = f"KAN-{i}"
    projectid = random.randint(1,5)
    
    rows.append([i,title,description,status,priority,assigned,
                 created.strftime("%Y-%m-%dT00:00:00"),
                 updated.strftime("%Y-%m-%dT00:00:00") if updated else "",
                 taskcode,projectid])

df = pd.DataFrame(rows, columns=["Id","Title","Description","Status","Priority","Assigned",
                                 "CreatedDate","UpdatedDate","TaskCode","ProjectId"])

